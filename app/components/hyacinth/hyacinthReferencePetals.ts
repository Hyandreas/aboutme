/**
 * Hand-traced visible surfaces from public/assets/hyacinth.png (1792 × 2688).
 *
 * The tracing grid below is the same image uniformly resized to 1280 × 1920.
 * `uv()` converts those measured landmarks to source-image UVs: origin at the
 * top left, u rightwards, v downwards. No flower-generating transforms are used.
 * Contours run around actual visible lobe edges, including folded/concave rims.
 * A contour closes implicitly; do not duplicate its first point before fitting.
 *
 * Depth is an artistic reconstruction hint, not a measured depth map. One unit
 * equals the projected width of the whole reference image, and positive values
 * face the original camera. `depth` is the ridge depth; `cup` is ridge minus rim.
 * Thus 0.1 is about 0.467 world units when the image has a 7-unit world height.
 * Occluded attachments and petal undersides require inferred completion. These
 * annotations do not claim that the photograph reveals their hidden anatomy.
 */

export type UV = readonly [u: number, v: number];

export type ReferenceCluster =
  | 'crown'
  | 'upper-left-stack'
  | 'upper-right-bell'
  | 'upper-left-front'
  | 'middle-left-front'
  | 'middle-right-bell'
  | 'middle-right-front'
  | 'lower-centre-front'
  | 'lower-left-flank'
  | 'lower-right-flank';

export type ReferencePetalForm =
  | 'folded-blade'
  | 'open-lobe'
  | 'recurved-lobe'
  | 'bell-wall'
  | 'inner-fold';

export interface PetalReference {
  readonly id: number;
  readonly name: string;
  readonly cluster: ReferenceCluster;
  readonly form: ReferencePetalForm;
  readonly contour: readonly UV[];
  readonly attachment: UV;
  readonly tip: UV;
  /** Runs from the attachment through the visible principal fold to the lip. */
  readonly ridge: readonly UV[];
  readonly depth: number;
  /** Sideways pose in radians; positive yaw turns the tip to image right. */
  readonly tilt: number;
  readonly cup: number;
  /** Signed return at the lip; negative returns away from the reference eye. */
  readonly curl: number;
  readonly depthProfile: {
    readonly attachment: number;
    readonly ridge: number;
    readonly rim: number;
    readonly thickness: number;
  };
  readonly pose: {
    readonly yawDegrees: number;
    readonly pitchDegrees: number;
  };
  readonly visibility: {
    /** Larger values win only where two reference contours overlap. */
    readonly layer: number;
    readonly occludedBy: readonly number[];
    readonly attachmentInferred: boolean;
  };
}

type PixelPoint = readonly [x: number, y: number];
type DepthProfile = readonly [attachment: number, ridge: number, rim: number, curl: number];
const uv = ([x, y]: PixelPoint): UV => [x / 1280, y / 1920];

function traced(
  id: number,
  name: string,
  cluster: ReferenceCluster,
  form: ReferencePetalForm,
  contour: readonly PixelPoint[],
  attachment: PixelPoint,
  tip: PixelPoint,
  ridge: readonly PixelPoint[],
  shape: DepthProfile,
  pose: readonly [yawDegrees: number, pitchDegrees: number],
  layer: number,
  occludedBy: readonly number[] = [],
  attachmentInferred = true,
): PetalReference {
  return {
    id, name, cluster, form,
    contour: contour.map(uv),
    attachment: uv(attachment),
    tip: uv(tip),
    ridge: ridge.map(uv),
    depth: shape[1],
    tilt: pose[0] * Math.PI / 180,
    cup: shape[1] - shape[2],
    curl: shape[3],
    depthProfile: {
      attachment: shape[0], ridge: shape[1], rim: shape[2], thickness: 0.0035,
    },
    pose: { yawDegrees: pose[0], pitchDegrees: pose[1] },
    visibility: { layer, occludedBy, attachmentInferred },
  };
}

